import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {createClient} from "@supabase/supabase-js";
import {typescriptLoader} from "../tests/helpers/load-typescript.mjs";
const db=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const check=({data,error})=>{assert.ifError(error);return data;};
const load=typescriptLoader({"@/lib/supabase/admin":{getSupabaseAdmin:()=>db}});
const {runningPeriod,addCalendarDays}=load("lib/garmin/running-summary.ts");
const {readTrainingContext}=load("lib/training/storage.ts");
const zone="America/Los_Angeles", period=runningPeriod(zone,"previous");
let uid;
try {
  uid=check(await db.auth.admin.createUser({email:`traini-week-note-${randomUUID()}@example.invalid`,email_confirm:true})).user.id;
  check(await db.from("profiles").upsert({id:uid,display_name:"Weekly note fixture",target_distance:"FULL",target_date:addCalendarDays(period.start,120),training_days:[1,2,3,4,5,6,7],long_run_day:7}));
  const snapshot=async()=>check(await db.rpc("weekly_review_snapshot",{p_user_id:uid,p_starts_on:period.start,p_timezone:zone}));
  const before=await snapshot();
  assert.match(before.closeoutRevision,/^[0-9a-f]{32}$/);
  const rev=check(await db.rpc("training_input_revision",{p_user_id:uid}));
  const body={p_user_id:uid,p_starts_on:period.start,p_timezone:zone,p_version:0,p_rpe:6,p_memo:"Weekly note, not a completed workout",p_request_id:randomUUID()};
  const saved=check(await db.rpc("save_weekly_coaching_note",body));
  assert.equal(saved.version,1);
  assert.equal(check(await db.rpc("save_weekly_coaching_note",body)).version,1);
  assert.match((await db.rpc("save_weekly_coaching_note",{...body,p_request_id:randomUUID()})).error.message,/weekly_note_changed/);
  assert.match((await db.rpc("save_weekly_coaching_note",{...body,p_memo:"Different payload"})).error.message,/weekly_note_changed/);
  const after=await snapshot();
  assert.equal(after.weeklyFeedback.memo,body.p_memo);
  assert.notEqual(after.revision,before.revision);
  assert.equal(after.closeoutRevision,before.closeoutRevision);
  assert.notEqual(check(await db.rpc("training_input_revision",{p_user_id:uid})),rev);
  check(await db.rpc("save_weekly_coaching_note",{...body,p_version:1,p_rpe:9,p_request_id:randomUUID()}));
  const context=await readTrainingContext(uid);
  assert.equal(context.weeklyFeedback.length,1);
  assert.equal(context.weeklyFeedback[0].startsOn,period.start);
  assert.equal(context.weeklyFeedback[0].rpe,9);
  assert.equal(context.goal.condition,null,"Weekly effort does not invent a current condition");
  assert.equal(context.workoutFeedback.length,0);
  assert.equal(check(await db.from("training_plans").select("id").eq("user_id",uid)).length,0);
  assert.equal(check(await db.from("training_generation_requests").select("id").eq("user_id",uid)).length,0);
  assert.ok((await db.rpc("save_weekly_coaching_note",{...body,p_starts_on:addCalendarDays(period.start,14),p_request_id:randomUUID()})).error);
  console.log("PASS: weekly note persistence, original week, idempotency, CAS, review/plan invalidation, stable closeout acknowledgement, context input and future denial. No workout completion or inference writes.");
} finally {if(uid) check(await db.auth.admin.deleteUser(uid));}
